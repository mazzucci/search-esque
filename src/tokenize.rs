/// Whether `unicode61` treats the character as a separator.
pub fn is_separator(c: char) -> bool {
    let cp = c as u32;
    let (mut lo, mut hi) = (0usize, SEPARATORS.len());
    while lo < hi {
        let mid = (lo + hi) / 2;
        let (a, b) = SEPARATORS[mid];
        if cp < a {
            hi = mid;
        } else if cp > b {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    false
}

